##
strip_terms <- function(formula) {
    attr_names <- names(attributes(formula))
    for (i in seq_along(attr_names)) {
        attr(formula, attr_names[i]) <- NULL
    }

    formula <- as.formula(formula)
    return(formula)
}

#' @title Control function for the \link{itnb} function.
#'
#' @description Creates a list of default options.
#'
#' @param method String: The method used to optimise the parameters, either \code{"em"} (default) or \code{"mle"}. NB: this is only relevant if an inflation is included in the model, otherwise the method will always use MLE \code{"mle"}.
#' @param trace Numeric (>= 0): Showing a trace every '\code{trace}' number of iterations.
#' @param tolerance Numeric (> 0): Convergence tolerance.
#' @param iteration_min Numeric (>= 0): The minimum number of allowed iterations.
#' @param iteration_max Numeric (>= '\code{iteration_min}'): The maximum number of allowed iterations.
#' @param steps Numeric (>= 0): The number of steps used when approximating the integral needed for the derivative of the overdispersion.
#' @param exact TRUE/FALSE: Should parameter optimisation use the exact gradient or finite difference?
#' @param overdispersion TRUE/FALSE: Should an overdispersion parameter be estimated?
#' @param save_data TRUE/FALSE: Should the data be stored in the return object?
#' @param save_trace TRUE/FALSE: Should the trace be stored in the return object?
#'
#' @return A list of default arguments for the \link{itnb} function.
#' @export
itnb_control <- function(method = "em", trace = 0, tolerance = 1e-6, iteration_min = 2, iteration_max = 100, steps = 100, exact = NULL, overdispersion = TRUE, save_data = TRUE, save_trace = TRUE) {
    if (!is.character(method)) {
        stop("'method' has to be a string.")
    }
    method <- tolower(method)

    if (!(method %in% c("em", "expectation-maximisation", "expectation-maximization", "mle", "maximum-likelihood"))) {
        stop("'method' has be set to 'em' or 'mle'.")
    }
    else if (method %in% c("em", "expectation-maximisation", "expectation-maximization")) {
        method = "em"
    }
    else if (method %in% c("mle", "maximum-likelihood")) {
        method = "mle"
    }

    ##
    if (!is.numeric(trace)) {
        stop("'trace' has to be numeric.")
    }

    trace <- ceiling(trace)

    ##
    if (!is.numeric(tolerance)) {
        stop("'tolerance' has to be numeric.")
    }

    if (tolerance < .Machine$double.eps) {
        stop("'tolerance' has to be bigger than twice machine epsilon.")
    }

    ##
    if (!is.numeric(iteration_min)) {
        stop("'iteration_min' has to be numeric.")
    }

    iteration_min <- ceiling(iteration_min)

    if (!is.numeric(iteration_max)) {
        stop("'iteration_min' has to be numeric.")
    }

    iteration_max <- ceiling(iteration_max)

    if (iteration_min > iteration_max) {
        stop("'iteration_max' has be larger than 'iteration_min'.")
    }

    ##
    if (!is.numeric(steps)) {
        stop("'steps' has to be numeric.")
    }

    steps <- ceiling(steps)

    ##
    if (is.null(exact)) {
        if (method == "em") {
            exact = FALSE
        }
        else {
            exact = TRUE
        }
    }

    if (!is.logical(exact)) {
        stop("'exact' has to be logical.")
    }

    ##
    if (!is.logical(overdispersion)) {
        stop("'overdispersion' has to be logical.")
    }

    ##
    if (!is.logical(save_trace)) {
        stop("'save_trace' has to be logical.")
    }

    ##
    if (!is.logical(save_data)) {
        stop("'save_data' has to be logical.")
    }

    ##
    res <- list(
        method = method, trace = trace, tolerance = tolerance,
        iteration_max = iteration_max, iteration_min = iteration_min,
        steps = steps, exact = exact, overdispersion = overdispersion,
        save_data = save_data, save_trace = save_trace
    )

    ##
    return(res)
}

#' @title itnb parameter estimation
#'
#' @description Parameter estimation for data generated by a r.v. following an inflated and truncated negative binomial distribution.
#'
#' @param formula \link{formula}: A formula specifying the model.
#' @param data \link{data.frame}: A data-set containing response and covariates.
#' @param i Numeric (>= 0): The inflation point.
#' @param t Numeric (>= 0): The truncation point.
#' @param link String: Specifying the link function, set to either \code{"identity"}, \code{"sqrt"}, \code{"log"} (default), or \code{"reciprocal"}.
#' @param control List: A control object (see \link{itnb_control}).
#'
#' @return An \link{itnb-object}.
#'
#' @example inst/examples/itnb_example.R
#'
#' @export
itnb <- function(formula, data = NULL, i = NULL, t = NULL, link = "log", control = list()) {
    UseMethod("itnb")
}

##
itnb_matrix <- function(X, y, i, t, link, control = list()) {
    control <- do.call(itnb_control, control)

    ##
    if (is.null(i)) {
        i <- -1
    }

    if (!is.numeric(i)) {
        stop("'i' has to be numeric.")
    }

    if (length(i) != 1) {
        warning("'i' needs to have length 1, only the first element is used.")
        i <- i[1]
    }

    i <- ceiling(i)

    ##
    if (is.null(t)) {
        t <- -1
    }

    if (!is.numeric(t)) {
        stop("'t' has to be numeric.")
    }

    if (length(t) != 1) {
        warning("'t' needs to have length 1, only the first element is used.")
        t <- t[1]
    }

    t <- ceiling(t)

    ##
    yi <- as.numeric(y == i)
    p <- mean(yi, na.rm = TRUE)

    if (link == "identity") {
        beta <- lm_fast_cpp(X[y != i, , drop = FALSE], y[y != i, , drop = FALSE])
        alpha <- sum((y[y != i, drop = FALSE] / (X[y != i, , drop = FALSE] %*% beta) - 1)^2) / length(y)
    }
    else if (link == "sqrt") {
        beta <- lm_fast_cpp(X[y != i, , drop = FALSE], sqrt(y[y != i, , drop = FALSE]))
        alpha <- sum((y[y != i, drop = FALSE] / (X[y != i, , drop = FALSE] %*% beta)^2 - 1)^2) / length(y)
    }
    else if (link == "log") {
        beta <- lm_fast_cpp(X[y != i, , drop = FALSE], log(y[y != i, , drop = FALSE]))
        alpha <- sum((y[y != i, drop = FALSE] / exp(X[y != i, , drop = FALSE] %*% beta) - 1)^2) / length(y)
    }
    else if (link == "reciprocal") {
        beta <- lm_fast_cpp(X[(y != i) & (y > 0), , drop = FALSE], 1 / (y[(y != i) & (y > 0), , drop = FALSE]))
        alpha <- sum((y[(y != i) & (y > 0), drop = FALSE] * (X[(y != i) & (y > 0), , drop = FALSE] %*% beta) - 1)^2) / length(y)
    }
    else {
        stop("'link' has to be set to either 'identity', 'sqrt', 'log', or 'reciprocal'.")
    }

    ##
    if (control[["overdispersion"]]) {
        ##
        if ((i < 0) | (i <= t)) {
            res <- mle_tnb_cpp(
                X = X[y != i, , drop = FALSE], y = y[y != i, , drop = FALSE],
                beta_0 = beta, theta_0 = 1 / alpha, p_0 = p,
                i = i, t = t, link = link,
                tolerance = control[["tolerance"]],
                steps = control[["steps"]], exact = control[["exact"]],
                trace = control[["trace"]]
            ) |> suppressWarnings()

            res[["iterations"]] <- NA
            res[["trace"]] <- NA
        }
        else if ((t < 0) | (i > t)) {
            if (control[["method"]] == "em") {
                res <- em_itnb_cpp(
                    X = X, y = y, yi = yi,
                    beta_0 = beta, theta_0 = 1 / alpha, p_0 = p,
                    i = i, t = t, link = link,
                    iteration_min = control[["iteration_min"]], iteration_max = control[["iteration_max"]],
                    tolerance = control[["tolerance"]],
                    steps = control[["steps"]], exact = control[["exact"]],
                    trace = control[["trace"]], save_trace = control[["save_trace"]]
                ) |> suppressWarnings()
            }
            else {
                res <- mle_itnb_cpp(
                    X = X, y = y,
                    beta_0 = beta, theta_0 = 1 / alpha, p_0 = p,
                    i = i, t = t, link = link,
                    tolerance = control[["tolerance"]],
                    steps = control[["steps"]], exact = control[["exact"]],
                    trace = control[["trace"]]
                ) |> suppressWarnings()

                res[["iterations"]] <- NA
                res[["trace"]] <- NA
            }
        }
        else {
            stop("How did we get here? Report with code 'itnb-opt'.")
        }
    }
    else {
        alpha <- 0.0

        ##
        if ((i < 0) | (i <= t)) {
            res <- mle_tpois_cpp(
                X = X[y != i, , drop = FALSE], y = y[y != i, , drop = FALSE],
                beta_0 = beta, p_0 = p,
                i = i, t = t, link = link,
                tolerance = control[["tolerance"]],
                steps = control[["steps"]], exact = control[["exact"]],
                trace = control[["trace"]]
            ) |> suppressWarnings()

            res[["iterations"]] <- NA
            res[["trace"]] <- NA
        }
        else if ((t < 0) | (i > t)) {
            if (control[["method"]] == "em") {
                res <- em_itpois_cpp(
                    X = X, y = y, yi = yi,
                    beta_0 = beta, p_0 = p,
                    i = i, t = t, link = link,
                    iteration_min = control[["iteration_min"]], iteration_max = control[["iteration_max"]],
                    tolerance = control[["tolerance"]],
                    steps = control[["steps"]], exact = control[["exact"]],
                    trace = control[["trace"]], save_trace = control[["save_trace"]]
                ) |> suppressWarnings()
            }
            else {
                res <- mle_itpois_cpp(
                    X = X, y = y,
                    beta_0 = beta, p_0 = p,
                    i = i, t = t, link = link,
                    tolerance = control[["tolerance"]],
                    steps = control[["steps"]], exact = control[["exact"]],
                    trace = control[["trace"]]
                ) |> suppressWarnings()

                res[["iterations"]] <- NA
                res[["trace"]] <- NA
            }
        }
        else {
            stop("How did we get here? Report with code 'itpois-opt'.")
        }

        res[["logtheta"]] <- NA
    }

    res[["control"]] <- control
    return(res)
}

#' @title itnb parameter estimation
#'
#' @description Parameter estimation for data generated by a r.v. following an inflated and truncated negative binomial distribution.
#'
#' @param formula \link{formula}: A formula specifying the model.
#' @param data \link{data.frame}: A data-set containing response and covariates.
#' @param i Numeric (>= 0): The inflation point.
#' @param t Numeric (>= 0): The truncation point.
#' @param link String: Specifying the link function, set to either \code{"identity"}, \code{"sqrt"}, \code{"log"} (default), or \code{"reciprocal"}.
#' @param control List: A control object (see \link{itnb_control}).
#'
#' @return An \link{itnb-object}.
#'
#' @method itnb formula
#' @rdname itnb
#'
#' @example inst/examples/itnb_example.R
#'
#' @export
itnb.formula <- function(formula, data = NULL, i = NULL, t = NULL, link = "log", control = list()) {
    ##
    #
    control <- do.call(itnb_control, control)

    ## Checks for 'data'
    #
    keep_formula <- TRUE
    if (is.null(data)) {
        data <- tryCatch(
            expr = {
                as.data.frame(as.matrix(model.frame(formula)))
            },
            error = function(e) {
                stop("'data' needs to be supplied when using 'formula'.")
            }
        )

        x_name <- paste0(attr(terms(formula), "term.labels"), ".")
        colnames(data) <- paste0("V", gsub(x_name, "", colnames(data)))
        colnames(data)[1] <- "y"

        formula <- paste(colnames(data)[1], "~", paste(colnames(data)[seq_along(colnames(data))[-1]], collapse = " + "))
        formula <- as.formula(formula)
        keep_formula <- FALSE
    }

    # Re-capture feature names when '.' is used in formula interface
    formula <- terms(formula, data = data)
    formula <- strip_terms(formula)

    ##
    #
    if ((is.null(i) | (i < 0)) & (is.null(t) | (t < 0))) {
        ##
        if (control[["overdispersion"]]) {
            warning("When both 'i' and 't' are 'NULL' the problem reduces to a regular negative binomial regression, see the 'glm.nb' function from the 'MASS' package.")
        }
        else {
            warning("When both 'i' and 't' are 'NULL' the problem reduces to a regular Poisson regression, see the 'glm' function.")
        }
    }

    ##
    #
    X <- model.matrix(formula, data)

    #
    y <- model.response(model.frame(formula, data))
    y <- as.matrix(y, nrow = nrow(data))

    ##
    #
    res <- itnb_matrix(X = X, y = y, i = i, t = t, link = link, control = control)
    res[["beta"]] <- structure(res[["beta"]] |> c(), .Names = colnames(X))

    ##
    #
    if (keep_formula) {
        res[["formula"]] <- formula
    }
    else {
        res[["formula"]] <- NA
    }

    #
    if (control[["save_trace"]] & !all(is.na(res[["trace"]]))) {
        #
        res[["trace"]] <- do.call("cbind", res[["trace"]]) |> as.data.frame()
        names(res[["trace"]])[grep("V", names(res[["trace"]]))] <- colnames(X)

        #
        res[["trace"]] <- cbind(Iteration = seq_len(nrow(res[["trace"]])) - 1, res[["trace"]])
    }
    else {
        res[["trace"]] <- NA
    }

    #
    if (control[["save_data"]]) {
        res[["data"]] <- list(X = X, y = y)
    }
    else {
        res[["data"]] <- NA
    }

    #
    if (res[["converged"]]) {
        res[["flag"]] <- NA
    }

    ##
    class(res) <- "itnb"
    return(res)
}

#' @title Prediction method for inflated and truncated negative binomial regression models
#'
#' @description Predict function for \link{itnb-object}'s, i.e., objects of class '\code{itnb}'.
#'
#' @param object \link{itnb-object}.
#' @param ... Additional arguments (see details).
#'
#' @details The additional arguments are:
#' \describe{
#'      \item{\code{newdata}}{\link{data.frame}: A data-set of covariates. NB: if set to '\code{NULL}' it will return the fitted values.}
#'      \item{\code{type}}{String: Specifying the scale of the predicted/fitted values, either \code{"link"} or \code{"response"}.}
#' }
#'
#' @return A vector of predicted values.
#'
#' @method predict itnb
#'
#' @export
predict.itnb <- function(object, ...) {
    dots <- list(...)

    ##
    if (is.null(dots[["type"]])) {
        type <- "response"
    }
    else if (!is.character(dots[["type"]])) {
        stop("'type' has to be a string, taking the values 'link' or 'response'.")
    }
    else if (!(dots[["type"]] %in% c("link", "response"))) {
        stop("'type' has to be a string, taking the values 'link' or 'response'.")
    }
    else {
        type <- dots[["type"]]
    }

    ##
    #
    if (any(is.null(dots[["newdata"]]))) {
        if (all(is.na(object[["data"]]))) {
            stop("The 'data' was not found. Set 'save_data = TRUE' in the 'itnb_control' function, and re-run the optimisation routine.")
        }

        newdata <- object[["data"]][["X"]]
    }
    else {
        if (all(is.na(as.list(object[["formula"]])))) {
            newdata <- as.matrix(dots[["newdata"]])
        }
        else {
            #
            formula <- as.formula(object[["formula"]])
            formula <- strip_terms(delete.response(terms(formula)))

            #
            newdata <- dots[["newdata"]]
            if (!is.data.frame(newdata)) {
                newdata <- as.data.frame(newdata)
            }

            #
            newdata <- model.matrix(formula, newdata)
        }
    }

    #
    link <- object[["link"]]

    beta <- coef(object, par = "beta")
    pred <- newdata %*% beta

    #
    if (type == "response") {
        if (link == "sqrt") {
            pred <- pred * pred
        }
        else if (link == "log") {
            pred <- exp(pred)
        }
        else if (link == "reciprocal") {
            pred <- 1 / pred
        }
    }

    #
    return(pred[, 1])
}

#' @title Fitted values for inflated and truncated negative binomial regression models
#'
#' @description Fitted function for \link{itnb-object}'s, i.e., objects of class '\code{itnb}'.
#'
#' @param object \link{itnb-object}.
#' @param ... Additional arguments (see details).
#'
#' @details The additional arguments is \code{type}: a string, specifying the scale of the predicted/fitted values, either \code{"link"} or \code{"response"}.
#'
#' @return A vector of fitted values.
#'
#' @method fitted itnb
#'
#' @export
fitted.itnb <- function(object, ...) {
    dots <- list(...)

    ##
    if (is.null(dots[["type"]])) {
        type <- "link"
    }
    else if (!is.character(dots[["type"]])) {
        stop("'type' has to be a string, taking the values 'link' or 'response'.")
    }
    else if (!(dots[["type"]] %in% c("link", "response"))) {
        stop("'type' has to be a string, taking the values 'link' or 'response'.")
    }
    else {
        type <- dots[["type"]]
    }

    ##
    return(predict(object, type = type))
}

#' @title Residuals for inflated and truncated negative binomial regression models
#'
#' @description Residual function for \link{itnb-object}'s, i.e., objects of class '\code{itnb}'.
#'
#' @param object \link{itnb-object}.
#' @param ... Additional arguments (see details).
#'
#' @details The additional argument is '\code{type}': a string specifying the scale of the residuals, either \code{"pearson"}, \code{"deviance"}, \code{"response"}, or \code{"link"}.
#'
#' @return A vector of residuals.
#'
#' @method residuals itnb
#'
#' @export
residuals.itnb <- function(object, ...) {
    dots <- list(...)

    ##
    if (is.null(dots[["type"]])) {
        type <- "pearson"
    }
    else if (!is.character(dots[["type"]])) {
        stop("'type' has to be a string, taking the values 'link' or 'response'.")
    }
    else if (!(dots[["type"]] %in% c("pearson", "deviance", "link", "response"))) {
        stop("'type' has to be a string, taking the values 'pearson', 'deviance', 'link', 'response'.")
    }
    else {
        type <- dots[["type"]]
    }

    ##
    if (all(is.na(object[["data"]]))) {
        stop("The 'data' was not found. Set 'save_data = TRUE' in the 'itnb_control' function, and re-run the optimisation routine.")
    }
    else {
        X <- object[["data"]][["X"]]
        y <- object[["data"]][["y"]]
    }

    ##
    link <- object[["link"]]
    if (type == "link") {
        if (link == "sqrt") {
            y <- sqrt(y)
        }
        else if (link == "log") {
            y <- log(y)
        }
        else if (link == "reciprocal") {
            y <- 1 / y
        }
    }

    pred <- predict(object, newdata = X, type = ifelse(type == "link", "link", "response")) |> unname()
    res <- y[, 1] - pred

    ##
    if (type == "deviance") {
        #
        alpha <- object[["alpha"]]
        p <- object[["p"]]

        #
        i <- object[["i"]]
        t <- object[["t"]]

        #
        ll_m <- ditnb(x = y[, 1], mu = pred, alpha = alpha, p = p, i = i, t = t, return_log = TRUE)
        ll_s <- ditnb(x = y[, 1], mu = y[, 1], alpha = alpha, p = p, i = i, t = t, return_log = TRUE)

        dev <- abs(2.0 * (ll_s - ll_m))
        res <- unname(sign(y[, 1] - pred) * sqrt(dev))
    }
    else if (type == "pearson") {
        alpha <- object[["alpha"]]

        s <- sqrt(pred * (1.0 + alpha * pred))
        res <- unname(res / s)
    }
    else {
        res <- unname(res)
    }

    return(res)
}

#' @title Summary of an inflated and truncated negative binomial regression model
#'
#' @description Summary function for \link{itnb-object}'s, i.e., objects of class '\code{itnb}'.
#'
#' @param object \link{itnb-object}.
#' @param ... Additional arguments (see details).
#'
#' @details The additional arguments are:
#' \describe{
#'      \item{\code{level}}{Numeric (> 0): The significance level.}
#'      \item{\code{bootstrap}}{TRUE/FALSE: Should confidence envelopes and hypothesis tests be performed by bootstrap?}
#'      \item{\code{B}}{Numeric (> 0): The number of simulations used to create the confidence envelopes and hypothesis tests.}
#'      \item{\code{parametric}}{TRUE/FALSE: Should the confidence envelopes and hypothesis tests be simulated using a parametric bootstrap?}
#'      \item{\code{trace}}{Numeric (>= 0): Showing a trace every '\code{trace}' number of iterations.}
#'      \item{\code{type}}{String: Specifying the scale of the residuals (see \link{residuals.itnb}).}
#' }
#'
#' @return A summary of an \link{itnb-object}.
#'
#' @method summary itnb
#'
#' @export
summary.itnb <- function(object, ...) {
    dots <- list(...)

    ##
    level <- dots[["level"]]
    if (is.null(level)) {
        level <- 0.95
    }
    sig_level <- (1 - level) / 2

    ##
    bootstrap <- dots[["bootstrap"]]
    if (is.null(bootstrap)) {
        bootstrap <- TRUE
    }

    if (bootstrap) {
        ##
        B <- dots[["B"]]
        if (is.null(B)) {
            B <- 199
        }
        ##
        parametric <- dots[["parametric"]]
        if (is.null(parametric)) {
            parametric <- FALSE
        }
    }

    ##
    trace <- dots[["trace"]]
    if (is.null(trace)) {
        trace <- 0
    }

    ##
    type <- dots[["type"]]
    if (is.null(type)) {
        type <- "deviance"
    }

    ##
    r <- residuals(object, type = type)
    f <- fitted.values(object)

    coefs <- coef(object)
    se <- sqrt(diag(object[["vcov"]]))

    if (bootstrap) {
        ci <- confint.itnb(object, level = NULL, B = B, parametric = parametric, trace = trace)

        ##
        betas <- lapply(
            seq_len(ncol(ci[["ci"]][["beta"]])),
            function(j) {
                b_j <- coefs[["beta"]][j]
                se_j <- se[j]

                beta_j <- ci[["ci"]][["beta"]][, j]
                se_beta_j <- sd(beta_j, na.rm = TRUE)

                z_obs_j <- b_j / se_beta_j
                z_boot_j <- (beta_j - b_j) / se_beta_j

                p_lower_j <- (sum(abs(z_obs_j) < abs(z_boot_j), na.rm = TRUE) + 1) / (length(beta_j) + 1)
                p_upper_j <- (sum(abs(z_obs_j) >= abs(z_boot_j), na.rm = TRUE) + 1) / (length(beta_j) + 1)
                p_j <- 2.0 * min(p_lower_j, p_upper_j)

                c(
                    mean(beta_j, na.rm = TRUE),
                    se_beta_j,
                    quantile(beta_j, probs = c(sig_level, 1 - sig_level), na.rm = TRUE),
                    mean(beta_j, na.rm = TRUE) / se_beta_j,
                    p_j
                )

            }) |>
            (\(z) do.call("rbind", z))() |>
            structure(.Dimnames = list(
                colnames(ci[["ci"]][["beta"]]),
                c("Estimate", "Std. Error", paste0(c("Lower (", "Upper ("), paste0(100 * c(sig_level, 1 - sig_level), "%"), c(")", ")")), "t-value", "Pr(>|t|)")
            ))

        if (object[["control"]][["overdispersion"]]) {
            alpha <- ci[["ci"]][["alpha"]] |>
                (\(z) c(
                    mean(z),
                    sd(z),
                    quantile(z, probs = c(sig_level, 1 - sig_level), na.rm = TRUE)
                ))() |>
                matrix(nrow = 1) |>
                structure(.Dimnames = list(
                    paste(rep(" ", max(nchar(colnames(ci[["ci"]][["beta"]])))), collapse = ""),
                    c("Estimate", "Std. Error", paste0(c("Lower (", "Upper ("), paste0(100 * c(sig_level, 1 - sig_level), "%"), c(")", ")")))
                ))
        }
        else {
            alpha <- matrix(nrow = 0, ncol = 0)
        }

        if (object[["i"]] > -1) {
            p <- ci[["ci"]][["p"]] |>
                (\(z) c(
                    mean(z),
                    sd(z),
                    quantile(z, probs = c(sig_level, 1 - sig_level), na.rm = TRUE)
                ))() |>
                matrix(nrow = 1) |>
                structure(.Dimnames = list(
                    paste(rep(" ", max(nchar(colnames(ci[["ci"]][["beta"]])))), collapse = ""),
                    c("Estimate", "Std. Error", paste0(c("Lower (", "Upper ("), paste0(100 * c(sig_level, 1 - sig_level), "%"), c(")", ")")))
                ))
        }
        else {
            p <- matrix(nrow = 0, ncol = 0)
        }
    }
    else {
        betas_ci <- qt(1 - sig_level / 2, df = length(r) - length(coefs$beta)) * se
        betas <- cbind(
            coefs[["beta"]],
            se,
            coefs[["beta"]] - betas_ci,
            coefs[["beta"]] + betas_ci,
            sqrt((coefs[["beta"]] / se)^2),
            pnorm(sqrt((coefs[["beta"]] / se)^2), lower.tail = FALSE)
        ) |>
            structure(
                .Dimnames = list(
                    names(coefs[["beta"]]),
                    c("Estimate", "Std. Error", paste0(c("Lower (", "Upper ("), paste0(100 * c(sig_level, 1 - sig_level), "%"), c(")", ")")), "z-value", "Pr(>|z|)")
                )
            )

        if (object[["control"]][["overdispersion"]]) {
            alpha <- matrix(
                c(log(1 / coefs[["alpha"]]), object[["logtheta"]]),
                nrow = 1
            ) |>
                structure(
                    .Dimnames = list(
                        paste(rep(" ", max(nchar(names(coefs[["beta"]])))), collapse = ""),
                        c("Estimate", "Std. Error")
                    )
                )
        }
        else {
            alpha <- matrix(nrow = 0, ncol = 0)
        }

        if (object[["i"]] > -1) {
        p_se <- sqrt(coefs[["p"]] * (1 - coefs[["p"]]) / length(r))
        p <- matrix(
            c(coefs[["p"]], p_se, max(0, coefs[["p"]] - pnorm(1 - sig_level / 2) * p_se), min(1, coefs[["p"]] + pnorm(1 - sig_level / 2) * p_se)),
            nrow = 1
        ) |>
            structure(
                .Dimnames = list(
                    paste(rep(" ", max(nchar(names(coefs[["beta"]])))), collapse = ""),
                    c("Estimate", "Std. Error", paste0(c("Lower (", "Upper ("), paste0(100 * c(sig_level, 1 - sig_level), "%"), c(")", ")")))
                )
            )
        }
        else {
            p <- matrix(nrow = 0, ncol = 0)
        }
    }

    ##
    res <- list(
        formula = object[["formula"]],
        link = object[["link"]],
        i = object[["i"]],
        t = object[["t"]],
        residuals = r,
        type = type,
        level = level,
        coefficients = betas,
        overdispersion = alpha,
        inflation = p,
        bootstrap = if (bootstrap) ci else NA,
        iterations = object[["iterations"]]
    )

    class(res) <- "summary.itnb"
    return(res)
}

#' @title Print Summary
#'
#' @description Print a \link{summary.itnb-object}, i.e., a summary of an \link{itnb-object}.
#'
#' @param x \link{summary.itnb-object}
#' @param ... Additional arguments (see \link{print} and \link{printCoefmat}).
#'
#' @return An invisible \code{NULL}.
#'
#' @method print summary.itnb
#'
#' @export
print.summary.itnb <- function(x, ...) {
    ##
    cat("\n")

    ##
    cat("Formula:\n", deparse(x[["formula"]]), "\n")
    cat("\n")

    cat("Link:\n", x[["link"]], "\n")
    cat("\n")

    cat("Inflation point:", ifelse(x[["i"]] < 0, NA, x[["i"]]), "\n")
    cat("\n")

    cat("Trunctation point:", ifelse(x[["t"]] < 0, NA, x[["t"]]), "\n")
    cat("\n")

    ##
    #
    res_type <- x[["type"]] |> tolower()
    substr(res_type, 1, 1) <- toupper(substr(res_type, 1, 1))

    cat(res_type, "residuals:", "\n")
    print(summary(x[["residuals"]]), ...)
    cat("\n")

    ##
    #
    cat("Coefficients:\n")
    printCoefmat(x[["coefficients"]], ...)
    cat("\n")

    #
    if (x[["i"]] > 0) {
        cat("Inflation coefficients:\n")
        printCoefmat(x[["inflation"]], ...)
        cat("\n")
    }

    #
    if (nrow(x[["overdispersion"]]) > 0) {
        if (!all(is.na(x[["bootstrap"]]))) {
            cat("Overdispersion:\n")
        }
        else {
            cat("Overdispersion (shown for log(1 / alpha)):\n")
        }
        print(x[["overdispersion"]], ...)
        cat("\n")
    }

    ##
    if (!all(is.na(x[["bootstrap"]]))) {
        cat("(Based on", x[["bootstrap"]][["B"]], ifelse(x[["bootstrap"]][["parametric"]], "parametric", "non-parametric"), "bootstrap samples => p-value lower bound of", paste0(format(2 / (x[["bootstrap"]][["B"]] + 1), digits = 3), ")."), "\n")
        cat("\n")
    }

    ##
    cat("Number of EM iterations:", x[["iterations"]], "\n")
    cat("\n")

    return(invisible(NULL))
}

#' @title Extract model coefficients
#'
#' @description Coefficients extraction function for \link{itnb-object}'s, i.e., objects of class '\code{itnb}'.
#'
#' @param object \link{itnb-object}.
#' @param ... Additional arguments (see details).
#'
#' @details The additional argument is '\code{param}': a string specifying which parameter should be returned by the function, either \code{"beta"}, \code{"alpha"}, or \code{"p"}.
#'
#' @return If '\code{param}' is \code{NULL} a list of all parameters will be returned, otherwise the function only returns the parameter specified by '\code{par}'.
#'
#' @method coef itnb
#'
#' @export
coef.itnb <- function(object, ...) {
    dots <- list(...)

    if (is.null(dots[["param"]])) {
        if (object[["control"]][["overdispersion"]]) {
            if (object$i > 0) {
                r <- object[c("beta", "alpha", "p")]
            }
            else {
                r <- object[c("beta", "alpha")]
            }
        }
        else {
            if (object$i > 0) {
                r <- object[c("beta", "p")]
            }
            else {
                r <- object[c("beta")]
            }
        }
    }
    else if (dots[["param"]] == "beta") {
        r <- object[["beta"]]
    }
    else if (dots[["param"]] == "alpha") {
        r <- object[["alpha"]]
    }
    else if (dots[["param"]] == "p") {
        r <- object[["p"]]
    }
    else {
        stop("'param' only takes the values 'beta', 'alpha', or 'p'.")
    }

    return(r)
}

#' @title Diagnostic Plots
#'
#' @description Diagnostic plots for inflated and truncated negative binomial regression models.
#'
#' @param x \link{itnb-object}.
#' @param ... Additional arguments (see details).
#'
#' @details The additional arguments are:
#' \describe{
#'      \item{\code{type}}{String: Either \code{"fit"} or \code{"trace"}, specifying whether to show diagnostic plots (similar to \link{plot.lm} for \link{glm}-objects) or trace for the EM-algorithm, respectively.}
#'      \item{\code{param}}{String: Specifying the parameter to show for the trace-plot.}
#' }
#'
#' @return An invisible \code{NULL}.
#'
#' @method plot itnb
#'
#' @export
plot.itnb <- function(x, ...) {
    ##
    #
    oldpar <- par(no.readonly = TRUE)
    on.exit(par(oldpar))

    ##
    #
    dots <- list(...)
    if (is.null(dots[["type"]])) {
        type <- "fit"
    }
    else {
        type <- dots[["type"]]
    }

    if (!(type %in% c("fit", "trace"))) {
        stop("'type' has to be equal to either 'fit' or 'trace'.")
    }

    ##
    #
    if (type == "fit") {
        ##
        #
        r <- residuals(x, type = "deviance")
        mr <- mean(r)
        sr <- sd(r)

        #
        N <- length(r)
        f <- predict(x, type = "link")

        #
        or <- sort(r)
        p <- (seq_len(N) - 0.5) / N
        tp <- qnorm(p, 0, 1)

        #
        qr_x <- qr(x$data$X)
        hat_x <- rowSums(qr.Q(qr_x)^2)
        leverage <- hat_x / (1 - hat_x)

        k <- length(unlist(coef(x)))
        ds <- (r^2 / k) * (hat_x / (1 - hat_x)^2)

        ##
        #
        par(mfrow = c(2, 2))
        plot(f, r, xlab = "Linear predictor", ylab = "Deviance residuals"); abline(h = 0, col = "dodgerblue2", lwd = 2)

        plot(tp, or, xlab = "Quantiles of standard normal distribtion", ylab = "Ordered deviance residuals"); abline(mr - sr * mean(tp), sr, col = "dodgerblue2", lwd = 2)

        plot(leverage, ds, xlab = "Leverage", ylab = "Cook's statistic", xlim = c(min(leverage, 3 * k / N - 1 / N), max(leverage, 3 * k / N + 1 / N)), ylim = c(min(ds, 4 / (N - k) - 1 / N), max(ds, 4 / (N - k) + 1 / N))); abline(v = 3 * k / N, col = "dodgerblue2", lwd = 2); abline(h = 4 / (N - k), col = "dodgerblue2", lwd = 2)

        plot(seq_len(N), ds, xlab = "Observation index", ylab = "Cook's statistic", ylim = c(min(ds, 4 / (N - k) - 1 / N), max(ds, 4 / (N - k) + 1 / N))); abline(h = 4 / (N - k), col = "dodgerblue2", lwd = 2)
    }
    else {
        if (is.na(x$iterations)) {
            stop("When 'type = \"trace\"' the method used to optimise the parameters has to be the EM-algorithm, i.e., 'method = \"em\"' has to be passed to the control object.")
        }

        x_trace <- x$trace[x$trace$Iteration > 0, , drop = FALSE]
        x_iteration <- x_trace$Iteration

        if (is.null(dots[["param"]])) {
            param <- "LogLikelihood"
        }
        else {
            param <- dots[["param"]]
        }

        if (param == "LogLikelihood") {
            y_trace <- x_trace$LogLikelihood
            ylab <- "Log-likelihood"
        }
        else if (param %in% c("Intercept", "(Intercept)")) {
            y_trace <- x_trace$`(Intercept)`
            ylab <- "Intercept"
        }
        else if (param %in% c("Inflation", "inflation", "p")) {
            y_trace <- x_trace$p
            ylab <- "Inflation"
        }
        else if (param %in% c("Overdispersion", "overdispersion", "alpha")) {
            y_trace <- x_trace$alpha
            ylab <- "Overdispersion"
        }
        else {
            y_trace <- x_trace[, param == colnames(x_trace)]
            ylab <- param
        }

        plot(x_iteration, y_trace, xlab = "Iteration", ylab = ylab, pch = 16)
        points(x_iteration, y_trace, type = "l")
    }

    ##
    #
    return(invisible(NULL))
}
